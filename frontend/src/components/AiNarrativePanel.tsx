import AutoAwesomeIcon from '@mui/icons-material/AutoAwesome';
import ThumbDownOutlined from '@mui/icons-material/ThumbDownOutlined';
import ThumbUpOutlined from '@mui/icons-material/ThumbUpOutlined';
import Box from '@mui/material/Box';
import IconButton from '@mui/material/IconButton';
import Paper from '@mui/material/Paper';
import Skeleton from '@mui/material/Skeleton';
import { useTheme } from '@mui/material/styles';
import Typography from '@mui/material/Typography';

import { formatDateTime } from '../lib/format';

export type AiStatus = 'OK' | 'UNAVAILABLE' | 'BLOCKED' | 'LOADING';

export const AI_DISCLAIMER = 'AI-generated by IBM Granite · may contain errors';
export const AI_UNAVAILABLE = 'AI explanation unavailable.';
export const AI_BLOCKED = 'This AI response was withheld by the safety checks.';

interface Props {
  status: AiStatus;
  /** Plain text from the AI service; rendered as text, never as HTML. */
  text?: string | null;
  modelId?: string | null;
  generatedAt?: string | null;
  /** Thumbs up/down are shown but disabled until feedback ships (P6). */
  feedbackEnabled?: boolean;
  onFeedback?: (helpful: boolean) => void;
  locale?: string;
  timeZone?: string;
}

/**
 * Tinted surface for AI-generated text (BP §10.10). The disclaimer is always visible, whatever
 * the status. It never contains data tables: verified numbers stay in ``VerifiedDataPanel``.
 */
export default function AiNarrativePanel({
  status,
  text,
  modelId,
  generatedAt,
  feedbackEnabled = false,
  onFeedback,
  locale,
  timeZone,
}: Props) {
  const theme = useTheme();
  const meta = [modelId, generatedAt ? formatDateTime(generatedAt, locale, timeZone) : null]
    .filter(Boolean)
    .join(' · ');

  let body;
  if (status === 'LOADING') {
    body = (
      <Box aria-busy="true" aria-label="AI explanation loading">
        <Skeleton width="90%" />
        <Skeleton width="75%" />
      </Box>
    );
  } else if (status === 'UNAVAILABLE') {
    body = <Typography>{AI_UNAVAILABLE}</Typography>;
  } else if (status === 'BLOCKED') {
    body = <Typography>{AI_BLOCKED}</Typography>;
  } else {
    body = <Typography sx={{ whiteSpace: 'pre-wrap' }}>{text ?? ''}</Typography>;
  }

  return (
    <Paper
      component="section"
      aria-label="AI-generated explanation"
      variant="outlined"
      sx={{
        bgcolor: theme.aiGenerated.background,
        borderColor: theme.aiGenerated.border,
        borderLeftWidth: 4,
        color: theme.aiGenerated.text,
        p: 2,
      }}
    >
      <Box sx={{ display: 'flex', alignItems: 'center', gap: 1 }}>
        <AutoAwesomeIcon fontSize="small" aria-hidden="true" />
        <Typography variant="subtitle2" component="h2" sx={{ fontWeight: 600 }}>
          {AI_DISCLAIMER}
        </Typography>
      </Box>
      {meta ? (
        <Typography variant="caption" component="p" sx={{ mb: 1 }}>
          {meta}
        </Typography>
      ) : null}
      <Box sx={{ mt: 1 }}>{body}</Box>
      <Box sx={{ display: 'flex', justifyContent: 'flex-end', gap: 0.5, mt: 1 }}>
        <IconButton
          size="small"
          aria-label="Helpful"
          disabled={!feedbackEnabled || status !== 'OK'}
          onClick={() => onFeedback?.(true)}
        >
          <ThumbUpOutlined fontSize="small" />
        </IconButton>
        <IconButton
          size="small"
          aria-label="Not helpful"
          disabled={!feedbackEnabled || status !== 'OK'}
          onClick={() => onFeedback?.(false)}
        >
          <ThumbDownOutlined fontSize="small" />
        </IconButton>
      </Box>
    </Paper>
  );
}
