// @vitest-environment node
/**
 * Freshness check (AC-4.7): ``src/api/schema.d.ts`` must be exactly what ``npm run gen:api``
 * generates from the committed contract ``docs/api/openapi-v1.json``. If this fails, run
 * ``npm run gen:api`` and commit the result (and log any contract change in STATUS).
 *
 * Generation uses openapi-typescript's programmatic API; the CLI only adds the header below.
 */
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import { describe, expect, it } from 'vitest';

import contract from '../../../docs/api/openapi-v1.json';
import committed from './schema.d.ts?raw';

const CLI_HEADER =
  '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';

const normalise = (text: string) => text.replace(/\r\n/g, '\n');

describe('generated API types', () => {
  it('match the committed OpenAPI contract', async () => {
    const generated = CLI_HEADER + astToString(await openapiTS(contract as unknown as OpenAPI3));
    expect(
      normalise(committed) === generated,
      'src/api/schema.d.ts is out of date: run `npm run gen:api` and commit it',
    ).toBe(true);
  }, 60_000);

  it('include the v1.1 capabilities field on /auth/me', () => {
    expect(committed).toMatch(/MeResponse: \{[^}]*capabilities: string\[\];/s);
  });
});
