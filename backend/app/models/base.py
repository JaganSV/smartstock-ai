"""Declarative base, naming convention and small column helpers."""

from datetime import datetime

from sqlalchemy import BigInteger, DateTime, Identity, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "ix": "ix_%(column_0_label)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def pk_id() -> Mapped[int]:
    """BIGINT GENERATED BY DEFAULT AS IDENTITY primary key."""
    return mapped_column(BigInteger, Identity(), primary_key=True)


def created_now() -> Mapped[datetime]:
    """TIMESTAMPTZ NOT NULL DEFAULT now() (server-side)."""
    return mapped_column(DateTime(timezone=True), server_default=func.now())
